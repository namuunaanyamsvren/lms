#!/usr/bin/env node
const fs = require('fs');
const path = require('path');

const backendRoot = path.resolve(__dirname, '..', '..');
const inventory = JSON.parse(fs.readFileSync(path.join(backendRoot, 'docs', 'api-route-inventory.generated.json'), 'utf8'));

const operationNames = inventory.routes
  .filter((route) => !route.path.includes('/health'))
  .map((route) => `  | '${route.method} ${route.path}'`)
  .join('\n');

const content = `// Generated by npm run api:types. Do not hand-edit.
export type ApiOperation =
${operationNames};

export type ApiEnvelope<T> = {
  success: boolean;
  data?: T;
  message?: string;
  code?: string;
  errors?: unknown;
};

export type ApiErrorCode =
  | 'VALIDATION_ERROR'
  | 'UNAUTHORIZED'
  | 'FORBIDDEN'
  | 'NOT_FOUND'
  | 'CONFLICT'
  | 'RATE_LIMITED'
  | 'INTERNAL_ERROR'
  | 'SERVICE_UNAVAILABLE';
`;

const outputPath = path.join(backendRoot, 'generated', 'api-client.d.ts');
fs.writeFileSync(outputPath, content);
console.log(`Wrote ${path.relative(path.resolve(backendRoot, '..'), outputPath)}`);
