#!/usr/bin/env node
const fs = require('fs');
const path = require('path');

const backendRoot = path.resolve(__dirname, '..', '..');
const root = path.resolve(backendRoot, '..');
const routeFiles = [
  ['auth', 'auth-service/src/routes/auth.routes.ts', '/api/v1/auth'],
  ['users', 'auth-service/src/routes/user.routes.ts', '/api/v1/users'],
  ['organizations', 'organization-service/src/routes/index.ts', '/api/v1/organizations'],
  ['academic', 'academic-service/src/routes/index.ts', '/api/v1'],
  ['notifications', 'notification-service/src/routes/index.ts', '/api/v1/notifications'],
  ['billing', 'billing-service/src/routes/index.ts', '/api/v1/payments'],
];

const methodPattern = /router\.(get|post|put|patch|delete)\(\s*['"`]([^'"`]+)['"`]/g;
const rolePattern = /requireRole\(([^)]*)\)/g;

function normalizePath(prefix, routePath) {
  const joined = routePath === '/' ? prefix : `${prefix}${routePath}`;
  return joined
    .replace(/\/+/g, '/')
    .replace(/:([A-Za-z0-9_]+)/g, '{$1}');
}

function nearestRoles(source, index) {
  const window = source.slice(Math.max(0, index - 300), Math.min(source.length, index + 500));
  const matches = [...window.matchAll(rolePattern)];
  if (!matches.length) return ['AUTHENTICATED'];
  return matches[matches.length - 1][1]
    .split(',')
    .map((role) => role.trim().replace(/^['"`]|['"`]$/g, ''))
    .filter(Boolean);
}

const routes = [];

for (const [service, relativeFile, prefix] of routeFiles) {
  const absoluteFile = path.join(backendRoot, relativeFile);
  const source = fs.readFileSync(absoluteFile, 'utf8');
  for (const match of source.matchAll(methodPattern)) {
    const method = match[1].toUpperCase();
    const routePath = normalizePath(prefix, match[2]);
    const publicRoute =
      routePath.includes('/health') ||
      routePath.includes('/csrf-token') ||
      routePath.includes('/login') ||
      routePath.includes('/register') ||
      routePath.includes('/refresh') ||
      routePath.includes('/forgot-password') ||
      routePath.includes('/reset-password') ||
      routePath.includes('/verify') ||
      routePath.includes('/google') ||
      routePath.includes('/organizations/onboard') ||
      routePath.includes('/organizations/resolve') ||
      routePath.includes('/provider-webhooks');
    routes.push({
      method,
      path: routePath,
      service,
      source: relativeFile,
      auth: publicRoute ? 'PUBLIC_OR_COOKIE' : 'BEARER',
      roles: publicRoute ? ['PUBLIC'] : nearestRoles(source, match.index),
    });
  }
}

routes.sort((a, b) => `${a.path} ${a.method}`.localeCompare(`${b.path} ${b.method}`));

const inventory = {
  generatedAt: new Date().toISOString(),
  routeCount: routes.length,
  routes,
};

const outputPath = path.join(backendRoot, 'docs', 'api-route-inventory.generated.json');
fs.writeFileSync(outputPath, `${JSON.stringify(inventory, null, 2)}\n`);
const tsOutputPath = path.join(backendRoot, 'gateway', 'src', 'openapi-route-inventory.generated.ts');
fs.writeFileSync(
  tsOutputPath,
  `// Generated by npm run openapi:inventory. Do not hand-edit.\nexport const generatedRouteInventory = ${JSON.stringify(inventory, null, 2)} as const;\n`,
);
console.log(`Wrote ${routes.length} routes to ${path.relative(root, outputPath)}`);
console.log(`Wrote ${path.relative(root, tsOutputPath)}`);
